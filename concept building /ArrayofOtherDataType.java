public class ArrayofOtherDataType {
    public static void main(String[] args) {
        char[] arr = new char[5];
        for (int i = 0; i < 5; i++) {
            System.out.println(arr[i]);
            
        }

        String[] strArr = {"Akansha ","Shivani "};
        for (int i = 0; i < strArr.length; i++) {
            System.out.println(strArr[i]);
        }
    }
}